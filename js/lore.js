(() => {
  const renamed = {};
  for (const id in MANGA_REFS) {
    const it = ITEMS[id];
    if (!it) continue;
    const [name, lore, fam] = MANGA_REFS[id];
    if (name && name !== it.name) { renamed[id] = it.name; it.name = name; }
    if (lore) it.lore = lore;
    if (fam) it.fam = fam;
  }
  // Names copied before this file ran: recipes, schematics, crafted scrolls, crop list.
  for (const k in SKILLS) for (const a of SKILLS[k].actions || []) if (renamed[a.id] && a.name === renamed[a.id]) a.name = ITEMS[a.id].name;
  for (const id in ITEMS) if (ITEMS[id].type === 'schematic' && ITEMS[ITEMS[id].teaches]) ITEMS[id].name = 'Schematic: ' + ITEMS[ITEMS[id].teaches].name;
  if (typeof CROPS !== 'undefined') for (const c of CROPS) if (renamed[c.id]) { c.name = ITEMS[c.id].name; if (ITEMS[c.seed]) ITEMS[c.seed].name = c.name + ' Seed'; }
})();
