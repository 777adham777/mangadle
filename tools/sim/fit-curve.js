#!/usr/bin/env node
// One curve for the whole game (2026-11-25). Every stage's foes are sized against the player the analytic
// run brings there (tools/sim: the reference player at the first fight in that stage, a guardian when it
// opens), with the same rules everywhere:
//   - a stage foe falls in TTK(s) seconds and costs LOSS(s) of your max HP (food pays for it);
//   - a guardian falls in BOSS_TTK(s) seconds, and its hardest blow is BOSS_BLOW × your auto-eat line:
//     the HP and defense of the world's armour and accessory are what let you stand it;
//   - the recommended level climbs evenly from 1 to 118 along the path, and a stage's XP is what it takes to
//     climb its share of levels in HOURS hours of fighting, so every world takes about as long;
//   - gold per kill is one exponential curve.
// Rounds: run → measure the reference player → write js/curve.js → run again (the player moves with the foes).
//   node tools/sim/fit-curve.js [rounds=5] [hoursPerStage=4]
'use strict';
const fs = require('fs'), path = require('path');
const { load, ROOT } = require('./load');
const rounds = +(process.argv[2] || 5), HOURS = +(process.argv[3] || 4);
const OUT = path.join(ROOT, 'js/curve.js');

const TTK = (s) => 6 + 0.15 * s;            // seconds for a stage foe
const LOSS = (s) => 0.035 + 0.0025 * s;     // share of your max HP a stage foe costs
const BOSS_TTK = (s) => 45 + 1.5 * s;       // seconds for a guardian
const BOSS_BLOW = 0.95;                     // its hardest blow / your auto-eat line in the world's armour and accessory
const GOLD = (s) => 15 * Math.pow(1.28, s); // gold per stage foe (×12 for a guardian)
const RESPAWN = 3;

function fit(C, rep) {
  const Z = C.__simZ;            // zones snapshot made inside the VM
  const stages = Z.filter((z) => !z.dungeon && z.n && z.id !== 'tear');   // the Rift Tear's foes change every hour (systems.js)
  const last = stages.length - 1, bossLast = stages.map((z, i) => (z.boss ? i : -1)).filter((i) => i >= 0).slice(-3)[0];
  const recOf = (i) => Math.min(120, Math.round(1 + 117 * Math.min(1, i / (bossLast || last))));
  const refs = rep.ref, known = stages.map((z) => refs[z.id]).map((r, i) => r && Object.assign({ i }, r)).filter(Boolean);
  // a stage the run never reached: the nearest reference below, scaled up by the growth seen so far
  const refAt = (i) => refs[stages[i].id] || (() => { const lo = known.filter((r) => r.i < i).pop() || known[0], g = Math.pow(1.08, i - lo.i);
    return Object.assign({}, lo, { maxHit: lo.maxHit * g, hp: lo.hp * g, def: lo.def * g, eat: lo.eat * g }); })();
  const out = {};
  stages.forEach((z, i) => {
    const P = refAt(i), mit = (d) => 100 / (100 + d), rec = recOf(i), rec2 = recOf(Math.min(last, i + 1));
    const dps = 0.75 * P.maxHit * mit(z.def * (P.edef || 1)) / P.speed * (P.tech || 1);
    const hitUnit = 0.75 * (P.taken || 1) * mit(P.def) * (1 - (P.dodge || 0)) / z.spd;   // your HP lost per second per point of foe attack
    const ttk = z.boss ? BOSS_TTK(i) : TTK(i);
    const hp = dps * ttk;
    const atk = z.boss ? BOSS_BLOW * (P.eatWith || P.eat) / ((P.taken || 1) * mit(P.defWith || P.def) * z.maxMove) : LOSS(i) * P.hp / (hitUnit * ttk);
    const kph = 3600 / (ttk + RESPAWN);
    const need = Math.max(1, C.XP_TABLE[Math.max(rec2, rec + 1)] - C.XP_TABLE[rec]);
    const xp = need / (HOURS * kph * (P.xm || 1)) * (z.boss ? 8 : 1);
    // what the game really ends up with (foes.js rescales foes by their moves, other passes touch gold): the
    // file's value is corrected by target / realised, so the game lands on the target
    // damped (×0.6 of the log step): the player moves with the foes, a full step oscillates
    const prev = PREV[z.id], fix = (k, target) => (prev && z.real[k] > 0 ? prev[k] * Math.pow(target / z.real[k], 0.6) : target);
    out[z.id] = { hp: Math.round(fix('hp', hp)), atk: Math.max(1, Math.round(fix('atk', atk))), xp: Math.max(1, Math.round(fix('xp', xp))), gold: Math.max(1, Math.round(fix('gold', GOLD(i) * (z.boss ? 12 : 1)))), rec };
  });
  return out;
}
function write(curve) {
  const lines = Object.entries(curve).map(([k, v]) => `  ${k}: { hp: ${v.hp}, atk: ${v.atk}, xp: ${v.xp}, gold: ${v.gold}, rec: ${v.rec} },`);
  fs.writeFileSync(OUT, `'use strict';
/* Generated by tools/sim/fit-curve.js: do not edit by hand (rerun the tool).
   One curve for every stage: average HP, attack, XP and gold of its foes, and its recommended level.
   Rules (same for every stage): a foe falls in 6 → 10.5 s and costs 3.5% → 11% of your max HP for the player
   you are when you get there; a guardian falls in 45 → 90 s and its hardest blow is 0.95 × your auto-eat
   line once you wear that world's best crafted armour and accessory (without them it drops you); levels
   climb evenly; gold grows ×1.28 a stage. */
const STAGE_CURVE = {
${lines.join('\n')}
};
`);
}
const snap = `globalThis.__simZ = ZONES.map((z) => { const k = (e) => (typeof kitOf === 'function' ? kitOf(e) : null);
  const mm = Math.max(1, ...z.enemies.map((e) => { const K = k(e); return K ? Math.max(1, ...(K.moves || []).concat((K.phases || []).map((p) => p.add).filter(Boolean)).map((m) => m.m || 0)) : 1; }));
  const av = (f) => z.enemies.reduce((a, e) => a + f(e), 0) / Math.max(1, z.enemies.length);
  return { id: z.id, real: { hp: av((e) => e.hp), atk: av((e) => e.atk), xp: av((e) => e.xp), gold: av((e) => (e.gold[0] + e.gold[1]) / 2) }, boss: !!z.boss, dungeon: !!z.dungeon, n: z.enemies.length, def: z.enemies.reduce((a, e) => a + e.def, 0) / Math.max(1, z.enemies.length), spd: z.enemies.reduce((a, e) => a + e.spd, 0) / Math.max(1, z.enemies.length), maxMove: mm }; });
  globalThis.XP_TABLE = XP_TABLE;`;
let rep, PREV = {};
for (let r = 0; r < rounds; r++) {
  const C = load({ patch: snap + ';globalThis.__curve = typeof STAGE_CURVE !== "undefined" ? STAGE_CURVE : {};' });
  PREV = C.__curve;
  rep = C.simRun({ maxH: 2000, stuckH: 168 });
  const gates = rep.events.filter(([, e]) => /^gate/.test(e)).map(([h, e]) => `${e.slice(5)} d${Math.floor((8 + h) / 24) + 1}`).join(' · ');
  console.log(`round ${r + 1}: path ${rep.goal}/${rep.goals} in ${rep.hours} h (day ${Math.floor((8 + rep.hours) / 24) + 1}) · ${gates}`);
  write(fit(C, rep));
}
console.log('wrote', OUT);
